# Converts IRIX desktop colour schemes (/usr/lib/X11/schemes/<Name>/BaseColorPalette) into the
# built-in themes table src/schemes.inc.
#
# usage: python3 -I gen_schemes.py <schemes dir> <out.inc>
#
# IRIX keeps three versions of every colour, one per system gamma (GAMMA_1_0, 1_7, 2_4) so that a
# scheme looks the same whatever gamma the workstation's display was set to. Windows applies no
# extra gamma ramp, which is the GAMMA_1_0 case - those are the values used here (they also match,
# pixel for pixel, screenshots of a real IRIX 6.5 desktop: #d8d8d8 window, #bdbdbd buttons and
# lists, #c5c1aa active 4Dwm frame).
#
# The IRIX 6.2-era scheme names that are exact copies of a 6.5 scheme (Lascaux = IndigoMagic,
# Leonardo = Bayou, Rembrandt = Mendocino, Turner = Potrero, VanGogh = Buckingham, Whistler =
# Gotham, Willis = BlackAndWhite apart from its message colours) are folded into that scheme as
# aliases, so old names in a settings file still resolve.
import os, re, sys

ROLES = [  # (C++ field, IRIX palette name)
    ('basic', 'BasicBackground'), ('text', 'TextForeground'), ('button', 'ButtonBackground'),
    ('textField', 'TextFieldBackground'), ('list', 'ScrolledListBackground'), ('trough', 'ScrollBarTroughColor'),
    ('sbControl', 'ScrollBarControlBackground'), ('indicator', 'IndicatorBackground'), ('radio', 'RadioColor'),
    ('check', 'CheckColor'), ('selectFill', 'SelectFillColor'), ('textSelBg', 'TextSelectedBackground'),
    ('textSelFg', 'TextSelectedForeground'), ('disabledText', 'DisabledTextForeground'), ('drawingArea', 'DrawingAreaBackground'),
    ('wmBg', 'WMBackground'), ('wmFg', 'WMForeground'), ('wmActiveBg', 'WMActiveBackground'), ('wmActiveFg', 'WMActiveForeground'),
    ('alt5', 'AlternateBackground5'), ('readOnly', 'ReadOnlyBackground'), ('textBg', 'TextBackground'),
    ('red', 'RedColor'), ('green', 'GreenColor'), ('blue', 'BlueColor'), ('orange', 'OrangeColor'),
]
# (folder, display name, aliases)
ORDER = [
    ('Base', 'Indigo Magic', ['IndigoMagic', 'Lascaux', 'Base']),
    ('Arizona', 'Arizona', []), ('Bayou', 'Bayou', ['Leonardo']), ('BlackAndWhite', 'Black and White', ['Willis']),
    ('Buckingham', 'Buckingham', ['VanGogh']), ('Gainsborough', 'Gainsborough', []), ('Gotham', 'Gotham', ['Whistler']),
    ('GrayScale', 'Gray Scale', []), ('Inverness', 'Inverness', []), ('KeyWest', 'Key West', []),
    ('Mendocino', 'Mendocino', ['Rembrandt']), ('Metropolis', 'Metropolis', []), ('Milan', 'Milan', []), ('Monet', 'Monet', []),
    ('Pacific', 'Pacific', []), ('Potrero', 'Potrero', ['Turner']), ('Print', 'Print', []), ('RedGreenSafe', 'Red-Green Safe', []),
    ('Rio', 'Rio', []), ('RoseGarden', 'Rose Garden', []), ('Sargent', 'Sargent', []), ('Titian', 'Titian', []),
    ('Vancouver', 'Vancouver', []),
]
DISPLAY_ALIAS = {'Lascaux': 'Lascaux', 'Leonardo': 'Leonardo', 'Rembrandt': 'Rembrandt', 'Turner': 'Turner',
                 'VanGogh': 'Van Gogh', 'Whistler': 'Whistler', 'Willis': 'Willis'}


def parse(path):
    top, secs, sec = {}, {}, None
    for line in open(path, errors='replace'):
        line = line.strip()
        m = re.match(r'#ifdef\s+(\w+)', line)
        if m:
            sec = m.group(1); secs.setdefault(sec, {}); continue
        if line.startswith('#endif'):
            sec = None; continue
        m = re.match(r'#define\s+(\w+)\s+(.*)$', line)
        if m:
            (secs[sec] if sec else top)[m.group(1)] = m.group(2).strip()
    return top, secs


def hexv(s):
    s = s.strip().lstrip('#')
    assert len(s) == 6, s
    return '0x' + s.lower()


root, out = sys.argv[1], sys.argv[2]
base_top, base = parse(os.path.join(root, 'Base', 'BaseColorPalette'))
rows = []
for folder, disp, aliases in ORDER:
    top, secs = parse(os.path.join(root, folder, 'BaseColorPalette'))
    g = dict(base['GAMMA_1_0'])        # older palettes omit a few roles: they inherit Base's
    g.update(secs['GAMMA_1_0'])
    desc = top['SchemeDescription']
    if folder == 'Base':
        desc = 'The default IRIX 6.5 desktop scheme'
    shown = [DISPLAY_ALIAS[a] for a in aliases if a in DISPLAY_ALIAS]
    if shown:
        desc += ' (also shipped as ' + ' and '.join(shown) + ')'
    dark = top.get('IsDarkScheme', 'FALSE').upper() == 'TRUE'
    vals = ', '.join(hexv(g[k]) for _, k in ROLES)
    key = 'IndigoMagic' if folder == 'Base' else folder
    al = '|'.join([key] + [a for a in aliases if a != key])
    rows.append(f'    {{L"{key}", L"{disp}", L"{desc}", L"{al}", {"true" if dark else "false"}, {{{vals}}}}},')

with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_schemes.py from the IRIX 6.5 desktop schemes\n')
    f.write('// (/usr/lib/X11/schemes/*/BaseColorPalette, GAMMA_1_0 values). Do not edit.\n')
    f.write('// Role order: ' + ' '.join(k for k, _ in ROLES) + '\n')
    f.write('static const SchemeDef kSchemes[] = {\n')
    f.write('\n'.join(rows) + '\n};\n')
    f.write(f'static const int kSchemeCount = {len(rows)};\n')
print(len(rows), 'schemes')
